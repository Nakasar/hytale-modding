#!/usr/bin/env python3
"""Génère les armes en argent infusé, fabriquées à l'établi des chasseurs (niveau 3, onglet Armes infusées).

    python3 mods/nakasar-vampires/tools/generate_infused_weapons.py [--preview FICHIER.png]

Chaque arme infusée hérite (Parent) de son arme en argent (generate_silver_weapons.py) : mêmes attaques et
dégâts de base. Elle s'en distingue par :
- le tag « Material: Infused_Silver » en plus de « Silver », que lit SilverDamageSystem (Java) : ×2,5 contre
  les vampires au lieu de ×2, et ×1,5 contre les autres morts-vivants (groupe Nakasar_Undead) ;
- l'apparence : texture et icône de l'arme en argent, parties métalliques réchauffées vers l'or pâle et
  icône cerclée d'un halo doré. L'épée en argent garde la texture et l'icône vanilla de l'épée en acier
  argenté (absentes du dépôt) : la sienne n'est pas repeinte ;
- la recette, écrite dans l'objet (sinon elle hériterait de celle de l'arme en argent) : l'arme en argent,
  2 lingots d'argent, 2 crocs de vampire et une topaze ;
- des textes à part (nakasar_infused.lang).

Lit les objets de Server/Item/Items/Weapon/Nakasar/Silver et nakasar_silver.lang, déjà dans le dépôt.
"""
import colorsys
import json
import re
import sys
from pathlib import Path

from PIL import Image, ImageFilter

PACK = Path(__file__).resolve().parent.parent / "src" / "main" / "resources"
COMMON = PACK / "Common"
SERVER = PACK / "Server"
SILVER_ITEMS = SERVER / "Item/Items/Weapon/Nakasar/Silver"
ITEMS = SERVER / "Item/Items/Weapon/Nakasar/Infused"
TEXTURES = "Items/Weapons/Nakasar/Infused"
ICONS = "Icons/Items/Nakasar/Infused"
CATEGORY_ICON = COMMON / "Icons/CraftingCategories/Nakasar/Infused_Silver.png"
LANG = "nakasar_infused"
BENCH = "Nakasar_Hunter_Workbench"
TAB = "Nakasar_Hunter_Weapons"
TIER = 3
GOLD = (255, 226, 140)

FR_SUFFIX = ("en argent", "en argent infusé")
DESCRIPTION_FR = ("Infusée par les chasseurs : ×2,5 dégâts contre les vampires, ×1,5 contre les autres morts-vivants. "
                  "Compte comme une arme en argent.")
DESCRIPTION_EN = ("Infused by the hunters: ×2.5 damage against vampires, ×1.5 against other undead. "
                  "Counts as a silver weapon.")


def infused_id(silver_id):
    return silver_id.removesuffix("_Silver") + "_Infused"


def warm(img, amount=0.45):
    """Parties métalliques (peu saturées, claires) tirées vers l'or pâle ; le reste est gardé."""
    img = img.convert("RGBA")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if a == 0:
                continue
            h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
            if s < 0.25 and l > 0.35:
                t = amount * min(1.0, (l - 0.35) / 0.4)
                px[x, y] = tuple(int(round(c + (gc - c) * t)) for c, gc in zip((r, g, b), GOLD)) + (a,)
    return img


def halo(icon):
    """Halo doré flou sous l'icône, visible sur son pourtour."""
    alpha = icon.getchannel("A").filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(1.6))
    glow = Image.new("RGBA", icon.size, GOLD + (0,))
    glow.putalpha(alpha.point(lambda v: int(v * 0.85)))
    glow.alpha_composite(icon)
    return glow


def read_lang(path):
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\s*([^#=\s][^=]*?)\s*=\s*(.*)$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def main():
    preview = Path(sys.argv[sys.argv.index("--preview") + 1]) if "--preview" in sys.argv else None
    fr = read_lang(SERVER / "Languages/fr-FR/nakasar_silver.lang")
    en = read_lang(SERVER / "Languages/en-US/nakasar_silver.lang")
    ITEMS.mkdir(parents=True, exist_ok=True)
    (COMMON / TEXTURES).mkdir(parents=True, exist_ok=True)
    (COMMON / ICONS).mkdir(parents=True, exist_ok=True)
    lang_fr = ["# Armes en argent infusé — textes français (générés par tools/generate_infused_weapons.py)"]
    lang_en = ["# Infused silver weapons — English texts (generated by tools/generate_infused_weapons.py)"]
    icons = []
    for path in sorted(SILVER_ITEMS.glob("*.json")):
        silver = json.loads(path.read_text(encoding="utf-8"))
        silver_id = path.stem
        if "Arrow" in silver.get("Tags", {}).get("Family", []):
            continue  # munition : pas de version infusée
        item_id = infused_id(silver_id)
        name = item_id.removeprefix("Weapon_Nakasar_")
        tags = json.loads(json.dumps(silver["Tags"]))
        tags["Material"] = tags.get("Material", []) + ["Infused_Silver"]
        item = {
            "Parent": silver_id,
            "TranslationProperties": {"Name": f"{LANG}.items.{item_id}.name",
                                      "Description": f"{LANG}.items.{item_id}.description"},
            "Quality": "Epic",
            "ItemLevel": silver.get("ItemLevel", 25) + 10,
            "Tags": tags,
            "Recipe": {
                "TimeSeconds": 4,
                "KnowledgeRequired": False,
                "Input": [{"ItemId": silver_id, "Quantity": 1},
                          {"ItemId": "Ingredient_Bar_Silver", "Quantity": 2},
                          {"ItemId": "Nakasar_Trophy_Vampire_Fang", "Quantity": 2},
                          {"ItemId": "Rock_Gem_Topaz", "Quantity": 1}],
                "BenchRequirement": [{"Type": "Crafting", "Id": BENCH, "Categories": [TAB], "RequiredTierLevel": TIER}],
            },
        }
        texture = COMMON / silver["Texture"]
        icon = COMMON / silver["Icon"]
        if texture.exists():
            warm(Image.open(texture)).save(COMMON / TEXTURES / f"{name}_Texture.png")
            item["Texture"] = f"{TEXTURES}/{name}_Texture.png"
        if icon.exists():
            out = halo(warm(Image.open(icon)))
            out.save(COMMON / ICONS / f"{item_id}.png")
            item["Icon"] = f"{ICONS}/{item_id}.png"
            icons.append(out)
        (ITEMS / f"{item_id}.json").write_text(json.dumps(item, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        silver_fr = fr[f"items.{silver_id}.name"]
        silver_en = en[f"items.{silver_id}.name"]
        name_fr = silver_fr.replace("d'argent", "d'argent infusé") if "d'argent" in silver_fr else silver_fr.replace(*FR_SUFFIX)
        name_en = "Infused " + silver_en
        lang_fr += [f"items.{item_id}.name = {name_fr}", f"items.{item_id}.description = {DESCRIPTION_FR}"]
        lang_en += [f"items.{item_id}.name = {name_en}", f"items.{item_id}.description = {DESCRIPTION_EN}"]
    (SERVER / f"Languages/fr-FR/{LANG}.lang").write_text("\n".join(lang_fr) + "\n", encoding="utf-8")
    (SERVER / f"Languages/en-US/{LANG}.lang").write_text("\n".join(lang_en) + "\n", encoding="utf-8")
    longsword = COMMON / ICONS / "Weapon_Nakasar_Longsword_Infused.png"
    Image.open(longsword).save(CATEGORY_ICON)
    if preview:
        sheet = Image.new("RGBA", (64 * len(icons), 64), (40, 40, 48, 255))
        for n, img in enumerate(icons):
            sheet.alpha_composite(img.resize((64, 64)), (64 * n, 0))
        sheet.resize((sheet.width * 2, 128), Image.NEAREST).save(preview)


if __name__ == "__main__":
    main()
